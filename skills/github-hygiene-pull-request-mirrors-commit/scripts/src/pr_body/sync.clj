(ns pr-body.sync
  "What `check` and `sync` decide, given the live pull request and the
  rendered title and body. Drift is compared byte for byte: no
  whitespace is normalised, so a hard wrap or a lost line break is
  drift. Only the questions of whether an unmarked body came from an
  older tool, and whether a body edited by hand is all in the commit
  message (`pr-body.fold`), compare whitespace-normalised text.

  A body edited by hand is never discarded: `sync` overwrites it once
  its text is in the commit message, or once a backup file holds it, for
  text dropped on purpose because it's no longer true of the commits."
  (:require [cheshire.core :as json]
            [clojure.string :as str]
            [pr-body.diff :as diff]
            [pr-body.fold :as fold]
            [pr-body.footer :as footer]))

(def diff-lines 8)

(defn in-sync? [live rendered]
  (and (= (:title live) (:title rendered)) (= (:body live) (:body rendered))))

(defn- normalize [s] (str/trim (str/replace (or s "") #"\s+" " ")))

(defn- without-attribution [s] (str/replace (or s "") #"\s*🤖[^\n]*\s*$" ""))

(defn legacy-bodies
  "The bodies an older tool would have written from `commits`: the old
  script's (one commit's `%b`, trailers included, reflowed) and
  `gh pr create --fill`'s (one commit's body, or a list of the commits'
  subjects in either order)."
  [commits]
  (let [subjects (map #(str "- " (:subject %)) commits)]
    (concat (map :raw-body commits)
            [(str/join "\n" subjects) (str/join "\n" (reverse subjects))])))

(defn legacy?
  "Whether `body` is, whitespace aside and with or without its last
  attribution line, one an older tool generated from `commits`."
  [body commits]
  (let [known (set (map normalize (legacy-bodies commits)))]
    (boolean (some #(known (normalize %)) [body (without-attribution body)]))))

(defn status
  "The live body's `pr-body.footer/edit-status`, `:generated` for an
  unmarked body an older tool generated from `commits`, or `:folded` for
  a body edited by hand whose text is all in `rendered-body`."
  [body commits rendered-body]
  (let [s (footer/edit-status body)]
    (cond
      (and (= s :unmarked) (legacy? body commits)) :generated
      (and (#{:edited :unmarked} s) (empty? (fold/missing body rendered-body))) :folded
      :else s)))

(defn- fold-advice
  "How to bring a body holding text the commit message doesn't back in
  line, where `save-command` saves the live body to `<file>`."
  [save-command]
  (str "Fold it into the commit message (git commit --amend), push with --force-with-lease and sync again. "
       "Text that is no longer true of the commits may be dropped instead: save the live body with\n  "
       save-command "\nand sync with --dropped-text-saved <file>."))

(defn status-note
  "A line saying whether a live body with status `s` may be re-synced."
  [s save-command]
  (case s
    :generated "The live body was generated by the old create-or-update-pull-request.sh or gh pr create --fill: safe to re-sync."
    :untouched "The live body is as this program generated it: safe to re-sync."
    :empty "The live body is empty: safe to re-sync."
    :folded "The live body was edited by hand, and its text is all in the commit message: safe to re-sync."
    (:edited :unmarked) (str "The live body holds text the commit message doesn't, so sync refuses it. "
                             (fold-advice save-command))))

(defn drift-report
  "What differs between `live` and `rendered`, for the pull request
  `label`, and whether the live body may be overwritten."
  [label live rendered s save-command]
  (str/join "\n"
            (concat
             [(str label " has drifted from its commits.")]
             (when s [(status-note s save-command)])
             (when (not= (:title live) (:title rendered))
               ["title:" (str "  PR:     " (:title live)) (str "  render: " (:title rendered))])
             (when (not= (:body live) (:body rendered))
               [(str "body diff (PR vs render, first " diff-lines " lines):")
                (diff/summary (:body live) (:body rendered) diff-lines)]))))

(defn saved?
  "Whether `text`, a backup file's contents, holds `body`, the live body
  of pull request `number`: a JSON object, as `gh pr view --json` writes
  it, whose `body` is `body` and whose `number`, if it has one, is
  `number`; or any other file whose text holds `body` whole."
  [text body number]
  (let [parsed (try (json/parse-string text) (catch Exception _ nil))]
    (if (and (map? parsed) (contains? parsed "body"))
      (and (= body (get parsed "body"))
           (or (not (contains? parsed "number")) (= number (get parsed "number"))))
      (and (not (str/blank? body)) (str/includes? text (str/trim body))))))

(defn plan
  "`{:action a :status s}` for `sync`, where `a` is `:create` (no open
  pull request), `:none` (already in sync), `:patch` or `:refuse`. A
  body this program or an older tool generated is safe to overwrite, and
  so is one edited by hand whose text is all in the commit message
  (`:folded`), or that `saved`, `{:text :number}` read from the
  `--dropped-text-saved` file, holds (`:saved`). Any other body edited
  by hand is refused: `:not-saved` when `saved` doesn't hold it."
  [live rendered commits saved]
  (cond
    (nil? live) {:action :create}
    (in-sync? live rendered) {:action :none}
    :else (let [s (status (:body live) commits (:body rendered))]
            (cond
              (not (#{:edited :unmarked} s)) {:action :patch :status s}
              (nil? saved) {:action :refuse :status s}
              (saved? (:text saved) (:body live) (:number saved)) {:action :patch :status :saved}
              :else {:action :refuse :status :not-saved}))))

(defn save-command
  "The command that saves pull request `number`'s live title and body to
  `<file>`."
  [slug number]
  (str "gh pr view " number " --repo " slug
       " --json url,number,title,body,headRefName,headRefOid,baseRefName,updatedAt > <file>"))

(defn refusal
  "The message for a refused sync of the pull request `label`."
  [{:keys [label live rendered status save-command saved-path]}]
  (if (= status :not-saved)
    (str saved-path " doesn't hold " label "'s live body, so it wasn't overwritten. Save it with\n  "
         save-command "\nand sync again with --dropped-text-saved <file>.")
    (str/join "\n"
              (concat
               [(str label "'s body holds text its commit message doesn't, so it wasn't overwritten:")]
               (map #(str "  \"" % "\"") (fold/missing (:body live) (:body rendered)))
               [(fold-advice save-command)]))))
